const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { PGlite } = require(process.env.PGLITE_MODULE || '@electric-sql/pglite');
(async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create schema storage;
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
      create function auth.role() returns text language sql stable as $$ select auth.jwt()->>'role' $$;
      create function public.is_app_email_allowed(text,text) returns boolean language sql stable as $$ select $1 = 'report' and $2 = 'staff@example.invalid' $$;
      create table public.students (id int); create table public.profiles (id int);
      create table public.news_articles (id int, status text, author_role text);
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint);
      create table storage.objects (id int, bucket_id text);
      insert into storage.buckets values ('mooe-receipts','mooe-receipts',true,null);
      insert into storage.objects values (1,'mooe-receipts');
      insert into public.students values (1); insert into public.profiles values (1);
      alter table public.students enable row level security; alter table public.profiles enable row level security;
      alter table public.news_articles enable row level security; alter table storage.objects enable row level security;
      create policy "Authenticated dashboard reads students" on public.students for select to authenticated using (true);
      create policy "Authenticated dashboard reads profiles" on public.profiles for select to authenticated using (true);
      create policy "Authenticated users read all articles" on public.news_articles for select to authenticated using (true);
      create policy "legacy writes" on public.news_articles for all to public using (true) with check (true);
      create policy "legacy storage" on storage.objects for all to public using (true) with check (true);
      create publication supabase_realtime;`);
    await db.exec(fs.readFileSync(path.join(__dirname, '../../supabase-homepage-slides.sql'), 'utf8'));
    const hardening = fs.readFileSync(path.join(__dirname, '../../supabase-portal-access-hardening.sql'), 'utf8');
    await db.exec(hardening); await db.exec(hardening);
    const receipts = fs.readFileSync(path.join(__dirname, '../../supabase-private-mooe-receipts.sql'), 'utf8');
    await db.exec(receipts); await db.exec(receipts);
    await db.exec(`create trigger news_articles_set_initial_status before insert on public.news_articles for each row execute function public.set_news_article_initial_status();
      grant usage on schema public, storage, auth to anon, authenticated;
      grant select, insert, update, delete on all tables in schema public, storage to anon, authenticated;
      set role authenticated; set request.jwt.claims = '{"role":"authenticated","email":"outsider@example.invalid"}';`);
    assert.equal((await db.query('select * from public.students')).rows.length, 0);
    assert.equal((await db.query('select * from public.profiles')).rows.length, 0);
    await assert.rejects(db.exec("insert into homepage_slides(image_url,storage_path) values('image','path')"), /row-level security/);
    assert.equal((await db.query("select * from storage.objects where bucket_id = 'mooe-receipts'")).rows.length, 0);
    await db.exec("insert into news_articles values(1,'approved','admin'); reset role;");
    assert.deepEqual((await db.query('select status, author_role from news_articles')).rows[0], { status: 'pending', author_role: 'student' });
    await db.exec(`set role authenticated; set request.jwt.claims = '{"role":"authenticated","email":"outsider@example.invalid"}';
      update news_articles set status = 'approved'; reset role;`);
    assert.equal((await db.query('select status from news_articles')).rows[0].status, 'pending');
    await db.exec(`set role authenticated; set request.jwt.claims = '{"role":"authenticated","email":"staff@example.invalid"}';`);
    assert.equal((await db.query('select * from public.students')).rows.length, 1);
    assert.equal((await db.query('select * from public.profiles')).rows.length, 1);
    assert.equal((await db.query("select * from storage.objects where bucket_id = 'mooe-receipts'")).rows.length, 1);
    await db.exec("update news_articles set status = 'approved'; insert into news_articles values(2,'pending','student'); reset role;");
    assert.equal((await db.query('select status from news_articles where id=2')).rows[0].status, 'approved');
    assert.equal((await db.query("select public from storage.buckets where id='mooe-receipts'")).rows[0].public, false);
    await db.exec(`set role anon; set request.jwt.claims = '{"role":"anon"}';`);
    assert.equal((await db.query("select * from storage.objects where bucket_id = 'mooe-receipts'")).rows.length, 0);
    console.log('PASS: migration reruns, report allowlist, blocked outsider reads/writes, forged news roles, staff moderation, and private receipts despite legacy policies.');
  } finally { await db.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
