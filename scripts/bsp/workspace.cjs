const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const dataDir = process.env.BSP_TEST_DATA_DIR;
app.setPath('userData', dataDir);
app.setPath('appData', app.getPath('userData'));
require('./cloud-fixture.cjs')(app.getPath('userData'));
const bsp = require('../../electron/bsp/main.cjs');
app.whenReady().then(async () => {
  try {
    await bsp.open();
    const win = BrowserWindow.getAllWindows()[0];
    const js = code => win.webContents.executeJavaScript(code);
    for (let i = 0; i < 100 && !await js('document.querySelector(\"#cloudStatus\")?.textContent.includes(\"Saved in Supabase\")'); i++) await new Promise(resolve => setTimeout(resolve, 25));
    assert.match(await js('document.getElementById("cloudStatus").textContent'), /Saved in Supabase/);
    assert.equal(await js('typeof window.bsp.printPreview'), 'function');
    assert.equal(await js('document.querySelector("h1").textContent'), 'Summary of Registration Fees');
    win.minimize();
    await bsp.open();
    assert.equal(win.isMinimized(), false, "Reopening restores a minimized workspace");
    assert.equal(BrowserWindow.getAllWindows().length, 1, 'Reuse the workspace to prevent concurrent local writers');
    await js("actions.nav({view: 'settings'})");
    assert.equal(await js('document.querySelector("h1").textContent'), 'Settings');
    assert.equal(await js("window.bsp.save(JSON.stringify(db))"), true);
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(dataDir, 'bsp-data.json'), 'utf8')), JSON.parse(await js('JSON.stringify(db)')));
    await js("go('unit'); const input = document.querySelector('#unitForm [name=sponsor]'); input.value = 'Unsaved school'; input.dispatchEvent(new Event('input', {bubbles:true}));");
    win.webContents.send('cloud:changed', { status: 'changed', message: 'Newer shared records are available.' });
    await new Promise(resolve => setTimeout(resolve, 50));
    assert.equal(await js("document.querySelector('#unitForm [name=sponsor]').value"), 'Unsaved school', 'Remote updates preserve unsaved form input');
    assert.equal(await js("document.querySelector('#unitForm [name=sponsor]').disabled"), false, 'Disconnected forms still accept drafts');
    assert.equal(await js("document.querySelector('#unitForm button[type=submit]').disabled"), true, 'Stale forms cannot submit');
    await js("window.confirm = () => false; document.querySelector('#cloudStatus button').click()");
    assert.equal(await js("document.querySelector('#unitForm [name=sponsor]').value"), 'Unsaved school', 'Cancelling reload keeps form input');
    await js("window.confirm = () => true; document.querySelector('#cloudStatus button').click()");
    for (let i = 0; i < 100 && !await js('document.getElementById("cloudStatus").textContent.includes("Saved in Supabase")'); i++) await new Promise(resolve => setTimeout(resolve, 25));
    await js("go('registration')");
    win.webContents.send('cloud:changed', {status:'offline',message:'Test disconnected workspace'});
    await new Promise(resolve => setTimeout(resolve, 50));
    assert.equal(await js("document.querySelector('#websiteRegistration [type=submit]').disabled"), false, 'No-payment registrations can be submitted without the payment workspace');
    assert.equal(await js("document.querySelector('#websiteRegistration [name=surname]').disabled"), false, 'Unpaid registration fields accept input');
    await js("const paidChoice = document.querySelector('[name=paymentStatus][value=paid]'); paidChoice.checked=true; paidChoice.dispatchEvent(new Event('change',{bubbles:true}))");
    assert.equal(await js("document.querySelector('#websiteRegistration [type=submit]').disabled"), true, 'Payment submissions still require shared receipt state');
    await js("document.querySelector('[name=paymentStatus][value=pending]').click()");
    assert.equal(await js("document.querySelector('#websiteRegistration [type=submit]').disabled"), false);
    const preview = await js("window.bsp.printPreview({html: '<div class=pg><h1>BSP Test</h1></div>', paper: 'A4'})");
    assert.equal(preview.ok, true, preview.reason);
    assert.ok(Buffer.from(preview.base64, 'base64').subarray(0, 4).toString() === '%PDF');
    const closed = new Promise(resolve => win.once('closed', resolve));
    bsp.close();
    await closed;
    assert.equal(BrowserWindow.getAllWindows().length, 0);
    console.log('PASS: integrated BSP launch, single workspace, settings, isolated storage, PDF preview, and close.');
    app.exit(0);
  } catch (err) { console.error(err); app.exit(1); }
});
